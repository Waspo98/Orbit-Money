package app.overbay.orbit.theme

import androidx.compose.material3.ColorScheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

/**
 * Complete resolved Material 3 [ColorScheme] and Orbit extended [CustomThemeColors] pair.
 */
@Immutable
data class ResolvedOrbitPalette(
    val colorScheme: ColorScheme,
    val customColors: CustomThemeColors
)

internal data class OrbitPresetSpec(
    val isDark: Boolean,
    val primary: Color,
    val onPrimary: Color,
    val primaryContainer: Color,
    val onPrimaryContainer: Color,
    val inversePrimary: Color,
    val secondary: Color,
    val onSecondary: Color,
    val secondaryContainer: Color,
    val onSecondaryContainer: Color,
    val tertiary: Color,
    val onTertiary: Color,
    val tertiaryContainer: Color,
    val onTertiaryContainer: Color,
    val background: Color,
    val onBackground: Color,
    val surface: Color,
    val onSurface: Color,
    val surfaceVariant: Color,
    val onSurfaceVariant: Color,
    val surfaceDim: Color,
    val surfaceBright: Color,
    val surfaceContainerLowest: Color,
    val surfaceContainerLow: Color,
    val surfaceContainer: Color,
    val surfaceContainerHigh: Color,
    val surfaceContainerHighest: Color,
    val inverseSurface: Color,
    val inverseOnSurface: Color,
    val outline: Color,
    val outlineVariant: Color,
    val error: Color,
    val onError: Color,
    val errorContainer: Color,
    val onErrorContainer: Color,
    val income: Color,
    val onIncome: Color,
    val incomeContainer: Color,
    val onIncomeContainer: Color,
    val warning: Color,
    val onWarning: Color,
    val warningContainer: Color,
    val onWarningContainer: Color,
    val canopyStart: Color,
    val canopyMid: Color,
    val canopyEnd: Color,
    val canopyGlow: Color,
    val canopyKicker: Color,
    val onCanopy: Color,
    val heroStatGood: Color = Color(0xFF8FF0C9),
    val heroStatWarn: Color = Color(0xFFFFE28A),
    val heroStatCaution: Color = Color(0xFFFFB3A8)
) {
    fun toPalette(): ResolvedOrbitPalette {
        val scheme = if (isDark) {
            darkColorScheme(
                primary = primary,
                onPrimary = onPrimary,
                primaryContainer = primaryContainer,
                onPrimaryContainer = onPrimaryContainer,
                inversePrimary = inversePrimary,
                secondary = secondary,
                onSecondary = onSecondary,
                secondaryContainer = secondaryContainer,
                onSecondaryContainer = onSecondaryContainer,
                tertiary = tertiary,
                onTertiary = onTertiary,
                tertiaryContainer = tertiaryContainer,
                onTertiaryContainer = onTertiaryContainer,
                background = background,
                onBackground = onBackground,
                surface = surface,
                onSurface = onSurface,
                surfaceVariant = surfaceVariant,
                onSurfaceVariant = onSurfaceVariant,
                surfaceTint = primary,
                inverseSurface = inverseSurface,
                inverseOnSurface = inverseOnSurface,
                error = error,
                onError = onError,
                errorContainer = errorContainer,
                onErrorContainer = onErrorContainer,
                outline = outline,
                outlineVariant = outlineVariant,
                scrim = Color.Black,
                surfaceBright = surfaceBright,
                surfaceDim = surfaceDim,
                surfaceContainerLowest = surfaceContainerLowest,
                surfaceContainerLow = surfaceContainerLow,
                surfaceContainer = surfaceContainer,
                surfaceContainerHigh = surfaceContainerHigh,
                surfaceContainerHighest = surfaceContainerHighest
            )
        } else {
            lightColorScheme(
                primary = primary,
                onPrimary = onPrimary,
                primaryContainer = primaryContainer,
                onPrimaryContainer = onPrimaryContainer,
                inversePrimary = inversePrimary,
                secondary = secondary,
                onSecondary = onSecondary,
                secondaryContainer = secondaryContainer,
                onSecondaryContainer = onSecondaryContainer,
                tertiary = tertiary,
                onTertiary = onTertiary,
                tertiaryContainer = tertiaryContainer,
                onTertiaryContainer = onTertiaryContainer,
                background = background,
                onBackground = onBackground,
                surface = surface,
                onSurface = onSurface,
                surfaceVariant = surfaceVariant,
                onSurfaceVariant = onSurfaceVariant,
                surfaceTint = primary,
                inverseSurface = inverseSurface,
                inverseOnSurface = inverseOnSurface,
                error = error,
                onError = onError,
                errorContainer = errorContainer,
                onErrorContainer = onErrorContainer,
                outline = outline,
                outlineVariant = outlineVariant,
                scrim = Color.Black,
                surfaceBright = surfaceBright,
                surfaceDim = surfaceDim,
                surfaceContainerLowest = surfaceContainerLowest,
                surfaceContainerLow = surfaceContainerLow,
                surfaceContainer = surfaceContainer,
                surfaceContainerHigh = surfaceContainerHigh,
                surfaceContainerHighest = surfaceContainerHighest
            )
        }

        val custom = CustomThemeColors(
            income = income,
            onIncome = onIncome,
            incomeContainer = incomeContainer,
            onIncomeContainer = onIncomeContainer,
            expense = onSurface,
            onExpense = background,
            expenseContainer = errorContainer,
            onExpenseContainer = onErrorContainer,
            danger = error,
            onDanger = onError,
            dangerContainer = errorContainer,
            onDangerContainer = onErrorContainer,
            warning = warning,
            onWarning = onWarning,
            warningContainer = warningContainer,
            onWarningContainer = onWarningContainer,
            transfer = onSurfaceVariant,
            onTransfer = background,
            canopyStart = canopyStart,
            canopyMid = canopyMid,
            canopyEnd = canopyEnd,
            canopyGlow = canopyGlow,
            canopyKicker = canopyKicker,
            onCanopy = onCanopy,
            cardBorder = outlineVariant,
            chartPositive = income,
            chartNegative = error,
            chartNeutral = onSurfaceVariant,
            chartGrid = if (isDark) Color(0x14FFFFFF) else Color(0x0F000000),
            heroStatGood = heroStatGood,
            heroStatWarn = heroStatWarn,
            heroStatCaution = heroStatCaution
        )
        return ResolvedOrbitPalette(colorScheme = scheme, customColors = custom)
    }
}
